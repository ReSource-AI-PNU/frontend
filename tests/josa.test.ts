test("단위는 읽는 소리로, 조사 표기는 여러 꼴을 받는다", () => {
  for (const [word, pair, expected] of [
    ["1,300 kg/월", "은는", "은"],
    ["1,300 kg", "이가", "이"],
    ["8%", "은는", "는"],
    ["320원/kg", "을를", "을"],
    ["2회/월", "으로", "로"],
    ["0.9 t", "이가", "이"],
    ["12 km", "은는", "는"],
  ] as const) {
    assert.equal(particle(word, pair), expected, word);
  }
  assert.equal(particle("수분", "은/는"), "은");
  assert.equal(particle("수분", "이(가)"), "이");
  assert.equal(particle("오염도", "를"), "를");
  assert.equal(particle("오염도", "로"), "로");
  assert.equal(particle("", "은는"), "는");
  assert.throws(() => particle("수분", "에게"));
});

